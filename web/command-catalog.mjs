export const commandCount = commandGroups.reduce((n,[,entries])=>n+entries.length,0);
export function searchCommands(query,category=""){
 const terms=query.trim().toLocaleLowerCase("ru").replace(/ё/g,"е").split(/\s+/).filter(Boolean);
 return commandGroups.filter(([name])=>!category||category===name).map(([name,entries])=>[name,entries.filter(entry=>{
  const hay=[name,...entry].join(" ").toLocaleLowerCase("ru").replace(/ё/g,"е");
  return terms.every(term=>hay.includes(term));
 })]).filter(([,entries])=>entries.length);
}
